use std::{fs, io::ErrorKind, path::Path};

use anyhow::{Context, Result, bail};
use clap::{Parser, Subcommand};
use nib_app::api::AppInfo;
use ts_rs::{Config, TS};

/// Development tasks for the nib workspace.
#[derive(Parser)]
#[command(name = "cargo xtask", version, about)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Generate TypeScript bindings from the Rust API types.
    Types {
        /// Verify committed bindings without writing files.
        #[arg(long)]
        check: bool,
    },
}

fn main() -> Result<()> {
    match Cli::parse().command {
        Command::Types { check } => types(check),
    }
}

/// Generate and verify the same content independently of the working directory.
fn types(check: bool) -> Result<()> {
    let workspace = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .context("xtask must live directly inside the workspace root")?;
    let output = workspace.join("apps/desktop/src/bindings/app-info.ts");
    let content = format!(
        "// Generated by `cargo xtask types`. Do not edit.\n\nexport {}\n",
        AppInfo::decl(&Config::new())
    );

    if check {
        let existing = match fs::read_to_string(&output) {
            Ok(existing) => existing,
            Err(error) if error.kind() == ErrorKind::NotFound => {
                bail!(
                    "{} is missing. Run `cargo xtask types` to generate it.",
                    output.display()
                );
            },
            Err(error) => {
                return Err(error).with_context(|| format!("read {}", output.display()));
            },
        };

        if existing != content {
            bail!(
                "{} is out of date. Run `cargo xtask types` to regenerate it.",
                output.display()
            );
        }

        println!("TypeScript bindings are up to date.");
        return Ok(());
    }

    let directory = output
        .parent()
        .context("the binding output must have a parent directory")?;
    fs::create_dir_all(directory).with_context(|| format!("create {}", directory.display()))?;
    fs::write(&output, content).with_context(|| format!("write {}", output.display()))?;
    println!("Generated {}", output.display());
    Ok(())
}
